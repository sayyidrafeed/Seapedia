/**
 * Production-like stack: prints a fresh .env.prod.local (random passwords, per-service RabbitMQ
 * and client-credentials secrets, identity's RS256 key pair as PEM with \n escapes).
 *   bun scripts/generate-secrets.ts > .env.prod.local
 *
 * Development: writes services/<svc>/.env, infra/seed/.env and infra/kong/.env from their
 * .env.example files plus one shared key pair. Existing .env files are left untouched.
 *   bun scripts/generate-secrets.ts --dev
 */
import { generateKeyPairSync, randomBytes } from 'node:crypto';

const secret = () => randomBytes(24).toString('hex');
const oneLine = (pem: string) => pem.trim().replace(/\n/g, '\\n');
const { privateKey, publicKey } = generateKeyPairSync('rsa', {
  modulusLength: 2048,
  publicKeyEncoding: { type: 'spki', format: 'pem' },
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
});

const lines = {
  IDENTITY_DB_PASSWORD: secret(),
  COMMERCE_DB_PASSWORD: secret(),
  CATALOG_DB_PASSWORD: secret(),
  CATALOG_DB_ROOT_PASSWORD: secret(),
  ELASTIC_PASSWORD: secret(),
  RABBITMQ_ADMIN_PASSWORD: secret(),
  RABBITMQ_IDENTITY_PASSWORD: secret(),
  RABBITMQ_CATALOG_PASSWORD: secret(),
  RABBITMQ_COMMERCE_PASSWORD: secret(),
  RABBITMQ_SEARCH_PASSWORD: secret(),
  CATALOG_CLIENT_SECRET: secret(),
  SEARCH_CLIENT_SECRET: secret(),
  SEED_CLIENT_SECRET: secret(),
  JWT_PRIVATE_KEY: `"${oneLine(privateKey)}"`,
  JWT_PUBLIC_KEY: `"${oneLine(publicKey)}"`,
  WEB_PORT: '8080',
  WEB_URL: 'http://localhost:8080',
  API_URL: 'http://localhost:3001',
  R2_ACCOUNT_ID: '',
  R2_ACCESS_KEY_ID: '',
  R2_SECRET_ACCESS_KEY: '',
  R2_BUCKET_NAME: '',
  R2_PUBLIC_DOMAIN: '',
};

if (process.argv.includes('--dev')) {
  const keys: Record<string, string> = { JWT_PRIVATE_KEY: lines.JWT_PRIVATE_KEY, JWT_PUBLIC_KEY: lines.JWT_PUBLIC_KEY };
  const targets = ['services/identity', 'services/catalog', 'services/commerce', 'services/search', 'infra/seed', 'infra/kong'];
  for (const dir of targets) {
    const target = Bun.file(`${dir}/.env`);
    if (await target.exists()) {
      console.log(`${dir}/.env exists, left as is`);
      continue;
    }
    const example = await Bun.file(`${dir}/.env.example`).text();
    const filled = example.replace(/^(JWT_PRIVATE_KEY|JWT_PUBLIC_KEY)=$/gm, (_, key: string) => `${key}=${keys[key]}`);
    await Bun.write(target, filled);
    console.log(`wrote ${dir}/.env`);
  }
} else {
  console.log('# Generated by scripts/generate-secrets.ts. Never commit this file.');
  for (const [key, value] of Object.entries(lines)) console.log(`${key}=${value}`);
}
